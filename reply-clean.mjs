// Очистка ответа YandexGPT перед озвучиванием + детерминированные гейты. Общая для
// turn-based (server.mjs) и стримингового (stream-server.mjs) путей — приветствие уже
// звучит в начале звонка, а слабая модель иногда дописывает фальшивые реплики обеих
// сторон, путает род и «закрывает» звонок без телефона. Промпт это до конца не держит
// (см. комментарий в prompt.mjs) — поэтому каждый наблюдавшийся сбой прикрыт кодом.

// YandexGPT зеркалит приветствие клиента в первом ответе, даже когда промпт это
// запрещает. Сценарий уже здоровается в начале звонка, поэтому срезаем ведущее
// приветствие из ответа — гарантированно, без надежды на модель.
const GREETING_RE =
  /^[\s—–-]*(здравствуй(?:те)?|добр(?:ый|ое|ого)\s+(?:день|утро|вечер|дня|времени\s+суток)|приветствую(?:\s+вас)?|привет)[\s,!.…—–-]*/iu;

export function stripGreeting(text) {
  const stripped = text.replace(GREETING_RE, "");
  if (stripped === text || stripped.length === 0) return text; // приветствия не было — не трогаем
  return stripped.charAt(0).toUpperCase() + stripped.slice(1);  // восстанавливаем заглавную букву
}

// Как stripGreeting, но БЕЗ страховки «вернуть оригинал, если осталось пусто». Нужно для
// потокового пути, где приветствие приходит ОТДЕЛЬНЫМ предложением ("Здравствуйте!"): его
// нужно превратить в "" и выбросить, а не оставить (иначе Ева здоровается в каждом ответе).
export function stripLeadingGreeting(text) {
  const stripped = text.replace(GREETING_RE, "");
  if (!stripped) return "";
  return stripped.charAt(0).toUpperCase() + stripped.slice(1);
}

// YandexGPT иногда «доигрывает» диалог за обе стороны и дописывает фальшивые реплики
// вида «Пользователь: …» / «Ассистент: …». Обрезаем ответ на первой такой метке:
// клиент должен услышать только первую реплику Евы.
// Формы: (1) метка с новой строки; (2) метка ВНУТРИ строки (после схлопывания переносов);
// (3) метка-ПРЕФИКС всего ответа: свою («Ева: …») срезаем, оставляя текст, чужую
// («Клиент: …» в самом начале) — выбрасываем весь ответ, это целиком выдуманная реплика
// клиента (пустую строку вызывающий код заменит на fallback-переспрос).
const ROLEPLAY_RE = /\n+\s*(?:пользовател[ья]|ассистент|клиент|оператор|ева|бот|собеседник|менеджер|user|assistant)\s*:/iu;
// Инлайн-метка засчитывается только ПОСЛЕ конца предложения: без этого честная фраза
// «Наш менеджер: Иван, он посчитает» обрубалась на «Наш» (метка посреди предложения —
// почти всегда живая речь, а не ролеплей).
const INLINE_ROLEPLAY_RE = /(?<=[.!?…]\s{1,3})(?:пользовател[ья]|ассистент|клиент|оператор|собеседник|ева|бот|менеджер|user|assistant)\s*:\s/iu;
const SELF_LABEL_PREFIX_RE = /^\s*(?:ева|ассистент|оператор|менеджер|бот|assistant)\s*:\s*/iu;
const OTHER_LABEL_PREFIX_RE = /^\s*(?:пользовател[ья]|клиент|собеседник|user)\s*:\s*/iu;

export function stripRolePlay(text) {
  if (OTHER_LABEL_PREFIX_RE.test(text)) return "";     // весь ответ — фальшивая реплика клиента
  let out = text.replace(SELF_LABEL_PREFIX_RE, "");    // «Ева: …» в начале — срезаем метку
  let cut = -1;
  for (const re of [ROLEPLAY_RE, INLINE_ROLEPLAY_RE]) {
    const m = out.match(re);
    if (m && m.index > 0) cut = cut < 0 ? m.index : Math.min(cut, m.index);
  }
  return cut > 0 ? out.slice(0, cut).trimEnd() : out;
}

// YandexGPT иногда отвечает markdown-разметкой (маркированные списки «* …», жирный
// «**…**»), хотя промпт это запрещает. TTS прочитал бы звёздочки вслух, поэтому срезаем
// разметку и превращаем список в связную фразу: убираем эмфазу, маркеры в начале строк,
// схлопываем переносы строк в пробелы.
export function stripMarkup(text) {
  return text
    .replace(/\*\*|__|`/g, "")               // жирный/код
    .replace(/^[ \t]*(?:[*\-•]|\d+[.)])[ \t]+/gmu, "") // маркеры/нумерация в начале строк
    .replace(/[*_]/g, "")                    // одиночные звёздочки/подчёркивания эмфазы
    .replace(/\s*\n+\s*/g, " ")              // переносы строк → пробел (телефонная речь без строк)
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

// YandexGPT иногда копирует примеры реплик из промпта вместе с обрамляющими
// кавычками-ёлочками «…» (примеры даны в «…»), и вся реплика приезжает в кавычках.
// Снимаем ОДНУ обёртку, только если кавычки именно обрамляют весь ответ (внутри нет
// второй открывающей «) — чтобы не тронуть внутреннее «Альфа Принт».
export function stripWrappingQuotes(text) {
  const t = text.trim();
  if (/^«[\s\S]*»$/.test(t) && (t.match(/«/g) || []).length === 1) return t.slice(1, -1).trim();
  if (/^"[\s\S]*"$/.test(t) && (t.match(/"/g) || []).length === 2) return t.slice(1, -1).trim();
  return text;
}

// Модель иногда говорит о Еве в мужском роде («понял») — мгновенно выдаёт бота.
// Чиним частотные маркеры согласия/состояния. Лукбехайнды-исключения защищают чужие
// подлежащие: «заказ будет готов», «менеджер передал» — мужской род тут ПРАВИЛЬНЫЙ,
// слепое феминизирование калечило валидные ответы («заказ будет готова»).
// \b в JS не работает с кириллицей, поэтому границу слова задаём lookaround по буквам.
const MASC_TO_FEM = [
  [/(?<![а-яёa-z])(?<!менеджер\s)(?<!он\s)понял(?![а-яёa-z])/giu, "поняла"],
  [/(?<![а-яёa-z])(?<!менеджер\s)(?<!он\s)записал(?![а-яёa-z])/giu, "записала"],
  [/(?<![а-яёa-z])услышал(?![а-яёa-z])/giu, "услышала"],
  [/(?<![а-яёa-z])уточнил(?![а-яёa-z])/giu, "уточнила"],
  [/(?<![а-яёa-z])(?<!менеджер\s)(?<!он\s)передал(?![а-яёa-z])/giu, "передала"],
  [/(?<![а-яёa-z])(?<!менеджер\s)(?<!он\s)сделал(?![а-яёa-z])/giu, "сделала"],
  [/(?<![а-яёa-z])рад(?![а-яёa-z])/giu, "рада"],
  [/(?<![а-яёa-z])(?<!будет\s)(?<!был\s)(?<!заказ\s)(?<!макет\s)(?<!вс[её]\s)(?<!он\s)готов(?![а-яёa-z])/giu, "готова"],
];

function matchCase(src, rep) {
  return /[А-ЯЁA-Z]/.test(src[0]) ? rep.charAt(0).toUpperCase() + rep.slice(1) : rep;
}

export function feminize(text) {
  let out = text;
  for (const [re, rep] of MASC_TO_FEM) out = out.replace(re, (m) => matchCase(m, rep));
  return out;
}

// Слитный номер в ответе («Повторю: 89674257979») alena читает как ОДНО гигантское
// числительное — сверить его на слух невозможно. Разворачиваем прогоны из 7+ цифр в
// цифры-слова через запятую: «восемь, девять, шесть…» — так номер и звучит «по цифрам»,
// как того требует промпт, независимо от того, послушалась ли модель.
const DIGIT_WORDS = ["ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"];

export function spellOutPhoneRuns(text) {
  return text.replace(/\+?\d[\d\s\-()]*\d/g, (run) => {
    const digits = run.replace(/\D/g, "");
    if (digits.length < 7) return run; // тиражи/размеры/цены не трогаем
    return digits.split("").map((d) => DIGIT_WORDS[+d]).join(", ");
  });
}

// Модель может «сорваться» во встроенный отказ Яндекса («как языковая модель…») — это
// мгновенно раскрывает бота, что прямо запрещено персоной. Детектим и подменяем реплику
// дежурным ответом Евы (тем же, что в промпте для «вы робот?»). Только САМОраскрытие
// (первое лицо / формула отказа): упоминание нейросети как темы («макет нейросетью —
// уточнит менеджер») — нормальная реплика, её глотать нельзя.
const BOT_LEAK_RE =
  /(как\s+языков[а-яё]*\s+модел|языков[а-яё]*\s+модел[а-яё]*[,\s]+я\s|я\s*[—–-]?\s*(?:бот|робот|программа|нейросеть|языков[а-яё]*\s+модел[а-яё]*|искусственн[а-яё]*\s+интеллект|виртуальн[а-яё]*\s+(?:помощник|ассистент))(?![а-яёa-z])|(?<![а-яёa-z])чат-?бот(?![а-яёa-z])|language\s+model)/iu;
export const BOT_DEFLECT = "Я Ева, из Альфа Принт, помогаю с заказами. Что нужно напечатать?";
export function hasBotLeak(text) { return BOT_LEAK_RE.test(text); }

// Полная очистка ответа: разметка → кавычки → фальшивый ролеплей → приветствие →
// женский род → номер по цифрам → защита от «я языковая модель».
export function cleanReply(text) {
  const cleaned = spellOutPhoneRuns(feminize(stripGreeting(stripRolePlay(stripWrappingQuotes(stripMarkup(text))))));
  return hasBotLeak(cleaned) ? BOT_DEFLECT : cleaned;
}

// ── Серверный гейт на телефон ────────────────────────────────────────────────────────
// Модель иногда «закрывает» заявку, пообещав обратный звонок, ещё НЕ взяв номер —
// горячий лид теряется. cleanReply историю не видит, поэтому гейт живёт здесь и
// принимает историю диалога.
// Глаголы-обещания заданы точными формами с границами слова: «позвоните нам» (императив
// клиенту) и «наберите нас» (тёплое прощание) сработать НЕ должны.
const PROMISES_CALLBACK_RE =
  /(перезвон|свяжется|свяжемся|свяжусь|позвонит(?![а-яёa-z])|позвоним(?![а-яёa-z])|набер[её]т(?![а-яёa-z])|набер[её]м(?![а-яёa-z])|соедин|переключ|менеджер[^.?!]{0,40}(?:позвон|набер|свяж))/iu;
// Просьба номера — только НАСТОЯЩИЕ просьбы. Раньше хватало голого «номер», и
// галлюцинация «перезвонит по указанному номеру» (номера никто не давал) проходила гейт.
const ASKS_FOR_PHONE_RE =
  /(продиктуйте|диктуйте|оставьте[^.?!]{0,25}(?:номер|телефон)|(?:какой|на какой)[^.?!]{0,20}(?:номер|телефон)|(?:назовите|скажите|подскажите|напомните)[^.?!]{0,25}(?:номер|телефон)|(?:номер|телефон)[^.?!]{0,25}(?:продиктуйте|записать|запишу))/iu;
const NUM_WORDS_RE = /(?<![а-яёa-z])(ноль|один|два|три|четыре|пять|шесть|семь|восемь|девять)(?![а-яёa-z])/giu;
// Отказ клиента ОТ ЗВОНКА/НОМЕРА («я подумаю», «сам перезвоню», «не надо звонить»):
// после второго такого гейт замолкает — третья просьба номера подряд превращает
// «настойчивого закрывающего» в навязчивого бота. Обычные «не надо/не нужно» про опции
// заказа («дизайн не надо») отказом НЕ считаются — иначе два бытовых отказа от допуслуг
// выключали страховку лида посреди активного заказа.
const REFUSAL_RE =
  /(подума[а-яё]*|сам[аи]?\s+(?:позвон|набер|перезвон)|не\s+(?:надо|нужно|буду)[^.?!]{0,25}(?:звон|номер|телефон)|(?:звонить|перезванивать)\s+не\s+(?:надо|нужно))/iu;

// Есть ли телефон в репликах клиента. Цифры считаем СПЛОШНЫМ прогоном (разделители
// пробел/скобки/дефис игнорируем): «90 на 50, тираж 1000» — это 8 цифр вразброс, но НЕ
// телефон; раньше такое ложно удовлетворяло гейт, и Ева закрывала звонок без номера.
// Номер, продиктованный в ДВА захода (пауза посреди номера режется ASR на две реплики),
// ловим склейкой цифровых хвоста и головы соседних реплик — и словами-цифрами тоже.
const squashDigits = (s) => String(s).replace(/[\s\-().+]/g, "");

export function hasPhone(history) {
  const users = history.filter((m) => m.role === "user").map((m) => String(m.text ?? ""));
  for (const t of users) {
    if (/\d{7,}/.test(squashDigits(t))) return true;
    if ((t.match(NUM_WORDS_RE) || []).length >= 5) return true;
  }
  // Пороги склейки НАМЕРЕННО жёстче внутрирепликовых: «нужно 1000» + «500 листовок»
  // (4+3=7 цифр) — не телефон; настоящий разорванный номер даёт ≥9 цифр или ≥7 слов-цифр.
  for (let i = 1; i < users.length; i++) {
    const tail = (squashDigits(users[i - 1]).match(/\d+$/) || [""])[0];
    const head = (squashDigits(users[i]).match(/^\d+/) || [""])[0];
    if (tail.length >= 3 && head.length >= 3 && tail.length + head.length >= 9) return true;
    const w1 = (users[i - 1].match(NUM_WORDS_RE) || []).length;
    const w2 = (users[i].match(NUM_WORDS_RE) || []).length;
    if (w1 >= 2 && w2 >= 2 && w1 + w2 >= 7) return true;
  }
  return false;
}

// Ротация просьбы номера: гейт может сработать несколько раз за звонок, а дословный
// повтор одной и той же фразы — главный признак бота (на стриминговом пути это ещё и
// байт-в-байт одинаковый звук из PCM-кэша). Вариант выбирается детерминированно от
// длины истории — внутри звонка фразы чередуются, тесты воспроизводимы.
export const PHONE_ASKS = [
  "Давайте так — продиктуйте номер, и менеджер перезвонит с точным расчётом. На какой записать?",
  "Чтобы менеджер набрал вас с готовым расчётом, продиктуйте, пожалуйста, номер — записываю.",
  "Остался только телефон: продиктуйте номер, и я сразу передам заявку менеджеру.",
];

export function phoneAsk(history = []) {
  return PHONE_ASKS[history.length % PHONE_ASKS.length];
}

function refusalCount(history) {
  return history.filter((m) => m.role === "user" && REFUSAL_RE.test(m.text)).length;
}

// Просит ли текст продиктовать/оставить номер (для лукахеда стримингового гейта).
export function asksForPhone(text) {
  return ASKS_FOR_PHONE_RE.test(text);
}

// Нужно ли подменить реплику на просьбу номера: обещает звонок, сама номер не просит,
// номера в истории нет, и клиент ещё не отказался дважды (после второго отказа Ева
// отпускает — давить третьей просьбой нельзя, это ломает персону).
export function needsPhoneAsk(history, reply) {
  return PROMISES_CALLBACK_RE.test(reply)
    && !ASKS_FOR_PHONE_RE.test(reply)
    && !hasPhone(history)
    && refusalCount(history) < 2;
}

export function enforcePhoneGate(history, reply) {
  return needsPhoneAsk(history, reply) ? phoneAsk(history) : reply;
}
