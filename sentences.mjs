// Делит ответ на короткие предложения, чтобы синтезировать и отдавать их по очереди
// (Ева начинает говорить после первого предложения — это и есть снижение задержки).
// Перенос строки — тоже граница: модель иногда отвечает списком без точек
// («* Визитки\n* Баннеры»), и без этого такой ответ не делился бы вовсе.
//
// Точка после сокращения («г.», «ул.», «т.») — НЕ конец предложения: адрес из ФАКТОВ
// («г. Нальчик, ул. Тарчокова») раньше разлетался на огрызки, и TTS читал их с паузами
// посреди адреса. Фрагмент, оканчивающийся сокращением, приклеиваем к следующему.
// «д» и «п» намеренно НЕ в списке: «и т. д.» / «и т. п.» обычно ЗАКАНЧИВАЮТ предложение,
// и склейка со следующим давала одно бесконечное предложение (сокращение «т.» в списке —
// оно и склеивает «т.» с «д.»).
const ABBR_TAIL_RE = /(?:^|[\s(«"])(?:г|ул|кв|стр|пр|просп|пер|обл|тел|руб|коп|шт|т|см|мм|м|кг|мин|им|доб)\.$/iu;

export function splitSentences(text) {
  const parts = text
    .split(/\n+/)
    .flatMap((line) => line.match(/[^.!?…]+[.!?…]+|[^.!?…]+$/gu) || [])
    .map((s) => s.trim())
    .filter(Boolean);
  const out = [];
  for (const p of parts) {
    if (out.length && ABBR_TAIL_RE.test(out[out.length - 1])) out[out.length - 1] += " " + p;
    else out.push(p);
  }
  return out;
}

// SpeechKit v1 синтезирует ≤ ~250 символов за запрос: одно СЛИШКОМ длинное предложение
// молча роняло TTS, и Ева «проглатывала» кусок реплики. Режем длинный текст на куски по
// ближайшей запятой/пробелу до лимита — синтезируются по очереди, звучат слитно.
export function chunkForTts(text, max = 240) {
  const out = [];
  let rest = String(text).trim();
  while (rest.length > max) {
    const slice = rest.slice(0, max);
    let cut = Math.max(slice.lastIndexOf(", "), slice.lastIndexOf("; "));
    if (cut < max * 0.4) cut = slice.lastIndexOf(" ");
    if (cut <= 0) cut = max;
    out.push(rest.slice(0, cut + 1).trim());
    rest = rest.slice(cut + 1).trim();
  }
  if (rest) out.push(rest);
  return out;
}
