// Делит ответ на короткие предложения, чтобы синтезировать и отдавать их по очереди
// (Ева начинает говорить после первого предложения — это и есть снижение задержки).
// Перенос строки — тоже граница: yandexgpt-lite иногда отвечает списком без точек
// («* Визитки\n* Баннеры»), и без этого такой ответ не делился бы вовсе.
export function splitSentences(text) {
  return text
    .split(/\n+/)
    .flatMap((line) => line.match(/[^.!?…]+[.!?…]+|[^.!?…]+$/gu) || [])
    .map((s) => s.trim())
    .filter(Boolean);
}
